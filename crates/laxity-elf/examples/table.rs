//! write the object table for a binary, which is how profiles/<platform>.objects.toml is regenerated after a firmware build.
//!
//!   cargo run -p laxity-elf --example table -- <elf> <profile.toml> <laxity.toml> [image-sha256]
//!
//! the table carries the symbols that configuration declares and not the whole symbol table. this binary allocates over a thousand symbols, almost all of them HAL code in flash that no placement audit reads, and a file that large is neither hand writable nor diffable, which is the whole point of the format. the cost is that a symbol added to laxity.toml after the table was written is absent from it and reports as not placed, so the table is regenerated whenever the declaration changes.
#![forbid(unsafe_code)]

use laxity_core::application::ApplicationDocument;
use laxity_core::profile::Profile;
use laxity_elf::read_elf;
use laxity_elf::table::{write_table, ObjectTable};
use std::{error::Error, fs, path::Path};

fn main() {
    if let Err(error) = run() {
        eprintln!("{error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), Box<dyn Error>> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    if !(3..=4).contains(&args.len()) {
        return Err("usage: table <elf> <profile.toml> <laxity.toml> [image-sha256]".into());
    }
    // the model projection, because the names this file carries have to be the ones laxity.toml and the characterisation use rather than the display labels.
    let profile = Profile::from_toml(&fs::read_to_string(&args[1])?)?;
    let document = ApplicationDocument::load(&args[2])?;
    let declared: Vec<String> = document
        .object
        .iter()
        .flat_map(|object| object.symbol_names())
        .collect();

    let objects: Vec<_> = read_elf(Path::new(&args[0]), &profile.regions)?
        .into_iter()
        .filter(|entry| declared.iter().any(|name| *name == entry.object.name))
        .collect();
    let missing: Vec<&str> = declared
        .iter()
        .filter(|name| !objects.iter().any(|entry| entry.object.name == **name))
        .map(String::as_str)
        .collect();

    let table = ObjectTable {
        objects,
        platform: profile.platform.clone(),
        image_sha256: args.get(3).cloned(),
    };
    let mut header = vec![
        format!(
            "generated by: cargo run -p laxity-elf --example table -- {} {} {}",
            args[0], args[1], args[2]
        ),
        format!(
            "the symbols {} declares, taken out of {}, and not the whole symbol table.",
            args[2], args[0]
        ),
        "regenerate it after a firmware build and after any change to the declared symbols, since a symbol this file does not carry reports as not placed.".to_string(),
    ];
    // the symbols the declaration names and the binary does not are listed here rather than left to be inferred from a short table, since that gap is a real finding about the firmware and not a fault in the generator.
    if !missing.is_empty() {
        header.push(format!(
            "declared and not in this image: {}",
            missing.join(", ")
        ));
    }
    let header: Vec<&str> = header.iter().map(String::as_str).collect();
    print!("{}", write_table(&table, &profile.regions, &header));
    Ok(())
}
